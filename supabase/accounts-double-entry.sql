-- Double-entry journal foundation for the Accounts workspace.
-- Approved legacy income/expense entries are posted exactly once.
create table if not exists public.account_chart_of_accounts (
 id uuid primary key default gen_random_uuid(), institution text not null check(institution in('mosque','foundation')),
 account_code text not null, account_name text not null,
 account_type text not null check(account_type in('asset','liability','equity','income','expense')),
 is_system boolean not null default true, is_active boolean not null default true, created_at timestamptz not null default now(),
 unique(institution,account_code)
);
create table if not exists public.account_journal_entries (
 id uuid primary key default gen_random_uuid(), institution text not null check(institution in('mosque','foundation')),
 journal_no bigint generated by default as identity, journal_date date not null, description text not null default '',
 source_type text not null check(source_type in('ledger_entry','manual','transfer','adjustment')), source_id uuid,
 status text not null default 'posted' check(status in('posted','reversed')), created_by uuid references auth.users(id),
 created_at timestamptz not null default now(), unique(institution,journal_no), unique(source_type,source_id)
);
create table if not exists public.account_journal_lines (
 id uuid primary key default gen_random_uuid(), journal_id uuid not null references public.account_journal_entries(id) on delete restrict,
 institution text not null check(institution in('mosque','foundation')), account_code text not null, description text not null default '',
 debit numeric(16,2) not null default 0 check(debit>=0), credit numeric(16,2) not null default 0 check(credit>=0),
 created_at timestamptz not null default now(), check((debit>0 and credit=0) or (credit>0 and debit=0))
);
create index if not exists account_journal_entries_institution_date_idx on public.account_journal_entries(institution,journal_date desc);
create index if not exists account_journal_lines_journal_idx on public.account_journal_lines(journal_id);
create index if not exists account_journal_lines_institution_account_idx on public.account_journal_lines(institution,account_code);
insert into public.account_chart_of_accounts(institution,account_code,account_name,account_type)
select i.institution,a.code,a.name,a.kind from (values('mosque'),('foundation')) i(institution)
cross join (values('1000','নগদ তহবিল','asset'),('1010','ব্যাংক হিসাব','asset'),('1020','মোবাইল ব্যাংকিং','asset'),
('3000','প্রারম্ভিক/সংরক্ষিত তহবিল','equity'),('4000','সাধারণ আয়','income'),('4010','যাকাত ও সদকা আয়','income'),
('5000','সাধারণ ব্যয়','expense'),('5010','যাকাত/সদকা বিতরণ ব্যয়','expense')) a(code,name,kind)
on conflict(institution,account_code) do nothing;
alter table public.account_chart_of_accounts enable row level security;
alter table public.account_journal_entries enable row level security;
alter table public.account_journal_lines enable row level security;
drop policy if exists account_chart_read on public.account_chart_of_accounts;
create policy account_chart_read on public.account_chart_of_accounts for select to authenticated using(public.accounts_feature_access(institution,'m41',false) or public.account_module_permission(institution,array['m41','m50']));
drop policy if exists account_journal_read on public.account_journal_entries;
create policy account_journal_read on public.account_journal_entries for select to authenticated using(public.accounts_feature_access(institution,'m41',false) or public.account_module_permission(institution,array['m41','m50']));
drop policy if exists account_journal_lines_read on public.account_journal_lines;
create policy account_journal_lines_read on public.account_journal_lines for select to authenticated using(exists(select 1 from public.account_journal_entries j where j.id=journal_id));
grant select on public.account_chart_of_accounts,public.account_journal_entries,public.account_journal_lines to authenticated;
create or replace function public.post_approved_ledger_entry_to_journal()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare v_journal uuid; v_asset text; v_income text; v_expense text;
begin
 if new.status<>'approved' or old.status='approved' then return new; end if;
 v_asset:=case new.payment_method when 'bank' then '1010' when 'mobile_banking' then '1020' else '1000' end;
 v_income:=case when new.fund_category in('zakat','sadaqah') then '4010' else '4000' end;
 v_expense:=case when new.fund_category in('zakat','sadaqah') then '5010' else '5000' end;
 insert into public.account_journal_entries(institution,journal_date,description,source_type,source_id,created_by)
 values(new.institution,new.entry_date,coalesce(nullif(new.note,''),new.category)||' · '||coalesce(new.payer_or_payee,''),'ledger_entry',new.id,new.created_by)
 on conflict(source_type,source_id) do nothing returning id into v_journal;
 if v_journal is null then return new; end if;
 if new.entry_type='income' then
  insert into public.account_journal_lines(journal_id,institution,account_code,description,debit,credit)
  values(v_journal,new.institution,v_asset,new.category,new.amount,0),(v_journal,new.institution,v_income,new.category,0,new.amount);
 else
  insert into public.account_journal_lines(journal_id,institution,account_code,description,debit,credit)
  values(v_journal,new.institution,v_expense,new.category,new.amount,0),(v_journal,new.institution,v_asset,new.category,0,new.amount);
 end if; return new;
end;$$;
revoke all on function public.post_approved_ledger_entry_to_journal() from public,anon,authenticated;
drop trigger if exists ledger_entry_double_entry_post on public.ledger_entries;
create trigger ledger_entry_double_entry_post after update of status on public.ledger_entries
for each row when(new.status='approved' and old.status is distinct from new.status)
execute function public.post_approved_ledger_entry_to_journal();
do $$
declare r record; v_journal uuid; v_asset text; v_income text; v_expense text;
begin
 for r in select * from public.ledger_entries where status='approved'
 and not exists(select 1 from public.account_journal_entries j where j.source_type='ledger_entry' and j.source_id=ledger_entries.id)
 loop
  v_asset:=case r.payment_method when 'bank' then '1010' when 'mobile_banking' then '1020' else '1000' end;
  v_income:=case when r.fund_category in('zakat','sadaqah') then '4010' else '4000' end;
  v_expense:=case when r.fund_category in('zakat','sadaqah') then '5010' else '5000' end;
  insert into public.account_journal_entries(institution,journal_date,description,source_type,source_id,created_by)
  values(r.institution,r.entry_date,coalesce(nullif(r.note,''),r.category)||' · '||coalesce(r.payer_or_payee,''),'ledger_entry',r.id,r.created_by) returning id into v_journal;
  if r.entry_type='income' then
   insert into public.account_journal_lines(journal_id,institution,account_code,description,debit,credit)
   values(v_journal,r.institution,v_asset,r.category,r.amount,0),(v_journal,r.institution,v_income,r.category,0,r.amount);
  else
   insert into public.account_journal_lines(journal_id,institution,account_code,description,debit,credit)
   values(v_journal,r.institution,v_expense,r.category,r.amount,0),(v_journal,r.institution,v_asset,r.category,0,r.amount);
  end if;
 end loop;
end $$;
create or replace view public.account_trial_balance with(security_invoker=true) as
select c.institution,c.account_code,c.account_name,c.account_type,coalesce(sum(l.debit),0)::numeric(16,2) total_debit,
coalesce(sum(l.credit),0)::numeric(16,2) total_credit,(coalesce(sum(l.debit),0)-coalesce(sum(l.credit),0))::numeric(16,2) net_balance
from public.account_chart_of_accounts c left join public.account_journal_lines l on l.institution=c.institution and l.account_code=c.account_code
left join public.account_journal_entries j on j.id=l.journal_id and j.status='posted'
where c.is_active group by c.institution,c.account_code,c.account_name,c.account_type;
grant select on public.account_trial_balance to authenticated;
create or replace view public.account_journal_report with(security_invoker=true) as
select j.id,j.institution,j.journal_no,j.journal_date,j.description,j.source_type,j.source_id,j.status,j.created_at,
coalesce(sum(l.debit),0)::numeric(16,2) total_debit,coalesce(sum(l.credit),0)::numeric(16,2) total_credit
from public.account_journal_entries j left join public.account_journal_lines l on l.journal_id=j.id
group by j.id,j.institution,j.journal_no,j.journal_date,j.description,j.source_type,j.source_id,j.status,j.created_at;
grant select on public.account_journal_report to authenticated;
